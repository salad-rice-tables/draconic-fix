"""CoA class docs (data/coa/<class>.md 'Reference table') -> talent trees.
 data/coa/talent_trees.json : { key: {tabs: [{name, nodes: [{name, x, y, type, links:[name,...], spell}]}]} }
 CoAUI/TalentData.lua       : client data  CoAUI_Trees[key] = {tabs...}   (spell ids already +7000000)
 lua/coa_talents_data.lua   : same for the server (COA_TREES)
Node -> spell: the class' converted spell with the same name (lowest custom id)."""
import glob, json, os, re

D = r'C:\WowServer\Custom\data\coa'
CLIENT_ADDON = r'C:\Games\Wow\World of Warcraft\_retail_\Interface\AddOns\CoAUI'
KEYS = {'demon-hunter': 'demonhunter', 'knight-of-xoroth': 'knightofxoroth', 'son-of-arugal': 'sonofarugal', 'sun-cleric': 'suncleric', 'witch-doctor': 'witchdoctor', 'witch-hunter': 'witchhunter'}
spells = json.load(open(os.path.join(D, 'all_spells_raw.json'), encoding='utf-8'))
by_name = {}
for sid, s in spells.items():
    if int(sid) >= 300000:
        by_name.setdefault(s['name'].lower(), []).append(int(sid))
row = re.compile(r'^\| (.+?) \| (\w[\w ]*?) \| (Ability|Talent|TalentAbility) \| ([\d.]+), ([\d.]+|None) \| (.*?) \| (.*?) \|\s*$')
out = {}
for f in sorted(glob.glob(os.path.join(D, '*.md'))):
    k = os.path.basename(f)[:-3]
    k = KEYS.get(k, k)
    t = open(f, encoding='utf-8').read()
    if '### Reference table' not in t:
        continue
    tabs, order = {}, []
    for line in t.split('### Reference table')[1].split('\n'):
        m = row.match(line)
        if not m:
            continue
        name, tab, typ, x, y, pre, con = m.groups()
        if tab not in tabs:
            tabs[tab] = {}
            order.append(tab)
        tabs[tab][name] = {'name': name, 'x': float(x), 'y': float(y) if y != 'None' else 0.0, 'type': typ, 'links': con.strip(), 'spell': 0}
    res = []
    for tab in order:
        nodes = tabs[tab]
        names = sorted(nodes, key=len, reverse=True)
        for n in nodes.values():
            raw, links = n['links'], []
            for nm in names:                                  # greedy longest-name match inside the comma list
                if nm != n['name'] and nm in raw:
                    links.append(nm)
                    raw = raw.replace(nm, '', 1)
            n['links'] = links
            c = by_name.get(n['name'].lower())
            if c:
                n['spell'] = 7000000 + min(c)
        res.append({'name': tab, 'nodes': list(nodes.values())})
    out[k] = {'tabs': res}
json.dump(out, open(os.path.join(D, 'talent_trees.json'), 'w'))


def lua(v, ind=''):
    if isinstance(v, dict):
        return '{' + ', '.join(f'{kk} = {lua(vv)}' if re.match(r'^[A-Za-z_]\w*$', kk) else f'["{kk}"] = {lua(vv)}' for kk, vv in v.items()) + '}'
    if isinstance(v, list):
        return '{' + ', '.join(lua(x) for x in v) + '}'
    if isinstance(v, str):
        return '"' + v.replace('\\', '\\\\').replace('"', '\\"') + '"'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    return str(v)


body = 'CoAUI_Trees = ' + lua({k: {'tabs': [{'name': tb['name'], 'nodes': [{'name': n['name'], 'x': n['x'], 'y': n['y'], 'type': n['type'], 'links': n['links'], 'spell': n['spell']} for n in tb['nodes']]} for tb in v['tabs']]} for k, v in out.items()}) + '\n'
open(os.path.join(CLIENT_ADDON, 'TalentData.lua'), 'w', encoding='utf-8').write('-- generated by tools/coa_talents_parse.py\n' + body)
open(r'C:\WowServer\Custom\lua\coa_talents_data.lua', 'w', encoding='utf-8').write('-- generated by tools/coa_talents_parse.py\n' + body.replace('CoAUI_Trees', 'COA_TREES'))
for k, v in out.items():
    print(k, [(tb['name'], len(tb['nodes']), sum(1 for n in tb['nodes'] if n['spell'])) for tb in v['tabs']])
