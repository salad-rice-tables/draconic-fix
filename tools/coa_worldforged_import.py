"""CoA Worldforged pickups (modules/mod-worldforged-pickups) -> this Midnight server.
Replays the module's SQL (downloaded into <scratch>/coa/wf/all/*.sql, in file order) into a scratch schema cow_scratch (AzerothCore columns; see /tmp wf_scratch.py),
then copies the final state:
 gameobject_template  entry 900000000 + CoA entry, type 10 (goober: the click is handled by lua/worldforged_pickups.lua)
 gameobject           guid 960000000000000000 + CoA guid
 item                 our Worldforge item (world.worldforge_item.ascension_id -> item 9700001+), so only pickups whose item AND display exist in this client are imported
Writes lua/worldforged_pickups.lua (entry -> item, plus tools/worldforged_logic.lua).  usage: python coa_worldforged_import.py [apply|undo]"""
import json, sys, os
sys.path.append("C:/Users/<user>/AppData/Roaming/Python/Python314/site-packages")
import pymysql

EOFF, GOFF = 900000000, 960000000000000000
READY = r'C:\WowServer\Custom\data\coa\worldforged_ready.json'
MAN = r'C:\WowServer\Custom\data\coa\worldforged_import_manifest.json'
LUA = r'C:\WowServer\Custom\lua\worldforged_pickups.lua'
LOGIC = r'C:\WowServer\Custom\tools\worldforged_logic.lua'
s = pymysql.connect(host='127.0.0.1', user='root', password=os.environ.get('DB_PASSWORD', ''), database='cow_scratch').cursor()
c = pymysql.connect(host='127.0.0.1', user='root', password=os.environ.get('DB_PASSWORD', ''), database='world', autocommit=True)
w = c.cursor()
NL = chr(10)


def undo():
    w.execute("delete from gameobject where guid between %s and %s", (GOFF, GOFF + 99999999)); a = w.rowcount
    w.execute("delete from gameobject_template where entry between %s and %s", (EOFF, EOFF + 9999999)); b = w.rowcount
    if os.path.exists(LUA): os.remove(LUA)
    print('removed', a, 'spawns,', b, 'templates')


def apply():
    ready = [int(x) for x in json.load(open(READY))['both']]
    w.execute("select ascension_id,item from worldforge_item"); ours = dict(w.fetchall())
    s.execute("select Entry,Item from gameobject_loot_template"); loot = {}
    for e, i in s.fetchall():
        if i in ours: loot.setdefault(e, ours[i])
    undo()
    n_t = n_s = 0; mapping = {}
    for e in ready:
        if e not in loot: continue
        s.execute("select type,displayId,name,size from gameobject_template where entry=%s", (e,)); t = s.fetchone()
        ne = EOFF + e
        w.execute("insert into gameobject_template (entry,type,displayId,name,size,ScriptName) values (%s,10,%s,%s,%s,'')", (ne, t[1], t[2], t[3] or 1.0)); n_t += 1; mapping[ne] = loot[e]
        s.execute("select guid,map,position_x,position_y,position_z,orientation,rotation0,rotation1,rotation2,rotation3 from gameobject where id=%s", (e,))
        for g in s.fetchall():
            w.execute("insert into gameobject (guid,id,map,position_x,position_y,position_z,orientation,rotation0,rotation1,rotation2,rotation3,spawntimesecs,animprogress,state) values (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,120,0,1)", (GOFF + g[0], ne) + g[1:]); n_s += 1
    head = ("-- Worldforged pickups as in CoA (mod-worldforged-pickups): a world object named after the item it holds; each character takes each one once." + NL +
            "-- GENERATED by tools/coa_worldforged_import.py (the PICK table); the logic below is tools/worldforged_logic.lua." + NL + "local PICK = {" + NL)
    body = ''.join('  [%d] = %d,%s' % (k, v, NL) for k, v in sorted(mapping.items())) + '}' + NL
    open(LUA, 'w', encoding='utf-8').write(head + body + open(LOGIC, encoding='utf-8').read())
    json.dump({'templates': n_t, 'spawns': n_s}, open(MAN, 'w'))
    print('imported', n_t, 'pickup templates and', n_s, 'spawns')


if __name__ == '__main__':
    undo() if sys.argv[1:2] == ['undo'] else apply()
