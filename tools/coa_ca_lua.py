"""data/coa/ca_trees.json (exact CoA catalog from the client DBCs) -> layout + Lua data for the CoAUI client (TalentData.lua) and the server (coa_talents_data.lua).
Layout: row = longest prerequisite path (nodes with a gate sit at least on the gate's row), x spread over 10 columns ordered by the mean x of the parents.
Spell ids: custom CoA spells (>= 300000) are +7000000 in Midnight; lower ids are retail ids."""
import json, os, re

ROOT = r'C:\WowServer\Custom'
ADDON = r'C:\Games\Wow\World of Warcraft\_retail_\Interface\AddOns\CoAUI'
d = json.load(open(os.path.join(ROOT, 'data', 'coa', 'ca_trees.json')))
sp = json.load(open(os.path.join(ROOT, 'data', 'coa', 'all_spells_raw.json'), encoding='utf-8'))
ICON = json.load(open(os.path.join(ROOT, 'data', 'coa', 'dbc_spell_icons.json')))
mp = lambda i: 7000000 + i if (i >= 300000 or (i >= 90000 and str(i) in sp)) else i   # CoA custom ids (spec identity passives 92081+) are converted spells too
SHAPE = {'SpendCircle': 'c', 'SpendSquare': 's', 'SpendChoice': 'h'}


def layout(nodes):
    """Exact grid from the CoA DBC (PositionX = column, PositionY = row); links = prerequisites plus grid neighbours (client lines)."""
    pos = {n['id']: (n['px'] + 1.5, n['py'] + 1) for n in nodes}
    cell = {(n['px'], n['py']): n['id'] for n in nodes}
    links = {n['id']: [] for n in nodes}
    for n in nodes:   # parent = neighbour one row up (same/adjacent column) else same row to the left
        x, y = n['px'], n['py']
        for dx in (0, -1, 1):
            o = cell.get((x + dx, y - 1))
            if o:
                links[n['id']].append(o)
                break
        else:
            o = cell.get((x - 1, y))
            if o:
                links[n['id']].append(o)
    return pos, links


def lua(v):
    if isinstance(v, dict):
        return '{' + ', '.join(f'{k} = {lua(x)}' for k, x in v.items()) + '}'
    if isinstance(v, list):
        return '{' + ', '.join(lua(x) for x in v) + '}'
    if isinstance(v, str):
        return '"' + v.replace('\\', '\\\\').replace('"', '\\"') + '"'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, float):
        return ('%.2f' % v).rstrip('0').rstrip('.')
    return str(v)


trees = {}
for key, tabs in d['classes'].items():
    out_tabs = []
    for tname in sorted(tabs, key=lambda t: (t != 'Class', t)):
        nodes = [n for n in tabs[tname] if n['ranks'] or n['ae'] or n['te']]
        pos, links = layout(nodes)
        arr = []
        for n in nodes:
            first = n['ranks'][0] if n['ranks'] else 0
            nm = n['name'] or ((sp.get(str(first)) or {}).get('name', '')) or str(n['id'])
            arr.append({'id': n['id'], 'name': nm, 'x': pos[n['id']][0], 'y': pos[n['id']][1], 'sh': SHAPE.get(n['nodeType'], 'c'), 'ranks': [mp(r) for r in n['ranks']],
                        'ae': n['ae'], 'te': n['te'], 'lvl': n['level'], 'grp': n['group'], 'gae': n['gateAE'], 'gte': n['gateTE'], 'req': n['req'], 'lk': links[n['id']], 'ic': next((ICON[str(r)] for r in n['ranks'] if str(r) in ICON), 0), 'auto': 0 if (n['ae'] or n['te']) else 1})
        out_tabs.append({'name': tname, 'nodes': arr})
    trees[key] = {'tabs': out_tabs}
budget = {k: {l: v for l, v in b.items()} for k, b in d['budget'].items()}
