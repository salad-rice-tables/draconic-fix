"""Make the Necromancer a real, selectable class on the creation screen by repurposing retail class slot 15 (Traveler).
MAX_CLASSES in the core is 16, so classes 1..15 are the only valid ids; 15 is the free hidden one.
Writes sql/20261106_class_necromancer.sql (+_undo) and applies nothing by itself.
 hotfixes: chr_classes(15) from the Mage row (creatable flags) with Necromancer texts, 3 chr_specialization rows
           (Animation/Death/Rime), Runic Power added to chr_classes_x_power_types (push 1950300)
 world   : class_expansion_requirement / playercreateinfo / playercreateinfo_action / player_classlevelstats copied from Mage (class 8)"""
import csv, os, pymysql

W = r'C:\WowServer\Custom\data\wago'
OUT = r'C:\WowServer\Custom\sql\20261106_class_necromancer'
PUSH, BUILD, CID = 1950300, 69933, 15
H_CLASS, H_SPEC, H_POWER = 4119371148, 2685374048, 3224459983


def q(v):
    if v is None:
        return 'NULL'
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("\\", "\\\\").replace("'", "''") + "'"


mage = [r for r in csv.reader(open(os.path.join(W, 'ChrClasses.csv'), encoding='utf-8'))]
hdr, rows = mage[0], mage[1:]
m = dict(zip(hdr, [r for r in rows if r[hdr.index('ID')] == '8'][0]))
v = [m[k] for k in hdr]


def setc(name, val):
    v[hdr.index(name)] = val


setc('Name_lang', 'Necromancer'); setc('Filename', 'NECROMANCER'); setc('Name_male_lang', 'Necromancer'); setc('Name_female_lang', 'Necromancer')
setc('Description_lang', 'Dark caster who commands the dead with plague and frost. Raises skeletal minions, spreads disease and freezes foes. Uses Life Force to hold minions and Runic Power.')
setc('RoleInfoString_lang', 'Roles: |cffffffffRanged Damage|r')
setc('DisabledString_lang', 'This class is not available.')
setc('Hyphenated_name_male_lang', 'Necro-mancer'); setc('Hyphenated_name_female_lang', 'Necro-mancer')
setc('ID', '15'); setc('DefaultSpec', '1501'); setc('ClassColorR', '148'); setc('ClassColorG', '130'); setc('ClassColorB', '201')
setc('DisplayPower', '0'); setc('RolesMask', '8')
# creation-screen animation = Death Knight frost/unholy visuals (closest retail match); filename stays NECROMANCER (glue override in the client adds the button)
for k, val in (('Field_9_0_1_34490_018', '20769'), ('MaleCharacterCreationVisualFallback', '128790'), ('MaleCharacterCreationIdleVisualFallback', '132590'),
               ('FemaleCharacterCreationVisualFallback', '0'), ('FemaleCharacterCreationIdleVisualFallback', '0'), ('CharacterCreationIdleGroundVisualFallback', '0'),
               ('CharacterCreationGroundVisualFallback', '131787'), ('AlteredFormCharacterCreationIdleVisualFallback', '133291'), ('CharacterCreationAnimLoopWaitTimeMsFallback', '20000')):
    setc(k, val)
class_row = '(' + ', '.join(q(x) if i < 10 else x for i, x in enumerate(v)) + ', ' + str(BUILD) + ')'
# header columns of the DB table (position aligned with the csv)
cols = ['Name', 'Filename', 'NameMale', 'NameFemale', 'PetNameToken', 'Description', 'RoleInfoString', 'DisabledString', 'HyphenatedNameMale', 'HyphenatedNameFemale',
        'CreateScreenFileDataID', 'SelectScreenFileDataID', 'IconFileDataID', 'LowResScreenFileDataID', 'Flags', 'StartingLevel', 'SpellTextureBlobFileDataID', 'ArmorTypeMask',
        'CharStartKitUnknown901', 'MaleCharacterCreationVisualFallback', 'MaleCharacterCreationIdleVisualFallback', 'FemaleCharacterCreationVisualFallback',
        'FemaleCharacterCreationIdleVisualFallback', 'CharacterCreationIdleGroundVisualFallback', 'CharacterCreationGroundVisualFallback',
        'AlteredFormCharacterCreationIdleVisualFallback', 'CharacterCreationAnimLoopWaitTimeMsFallback', 'CinematicSequenceID', 'DefaultSpec', 'ID', 'HasStrengthBonus',
        'PrimaryStatPriority', 'DisplayPower', 'RangedAttackPowerPerAgility', 'AttackPowerPerAgility', 'AttackPowerPerStrength', 'SpellClassSet', 'ClassColorR', 'ClassColorG',
        'ClassColorB', 'RolesMask', 'DamageBonusStat', 'HasRelicSlot', 'VerifiedBuild']
assert len(cols) == len(v) + 1, (len(cols), len(v))

specs = [(1501, 'Animation', 'Summons and commands swarms of undead minions.', 0, 136187),
         (1502, 'Death', 'Plague damage over time and wasting decay.', 1, 136145),
         (1503, 'Rime', 'Frost lich caster channelling grave cold.', 2, 135846)]
spec_rows = [f"({q(n)}, {q(n)}, {q(d)}, {i}, {CID}, {o}, 0, 2, 0, {ic}, 3, 0, 0, 0, {BUILD})" for i, n, d, o, ic in specs]

sql = [f"-- Necromancer as a real class (slot 15 'Traveler' repurposed). Generated by coa_class_necromancer.py. push {PUSH}. Undo: {os.path.basename(OUT)}_undo.sql",
       f"DELETE FROM `hotfixes`.`hotfix_data` WHERE `Id` = {PUSH};",
       f"DELETE FROM `hotfixes`.`chr_classes` WHERE `ID` = {CID};",
       f"DELETE FROM `hotfixes`.`chr_specialization` WHERE `ClassID` = {CID};",
       "DELETE FROM `hotfixes`.`chr_classes_x_power_types` WHERE `ID` = 9501;",
       f"INSERT INTO `hotfixes`.`chr_classes` (`{'`, `'.join(cols)}`) VALUES\n{class_row};",
       "INSERT INTO `hotfixes`.`chr_specialization` (`Name`, `FemaleName`, `Description`, `ID`, `ClassID`, `OrderIndex`, `PetTalentType`, `Role`, `Flags`, `SpellIconFileID`, `PrimaryStatPriority`, `AnimReplacements`, `MasterySpellID1`, `MasterySpellID2`, `VerifiedBuild`) VALUES\n" + ",\n".join(spec_rows) + ";",
       f"INSERT INTO `hotfixes`.`chr_classes_x_power_types` (`ID`, `PowerType`, `ClassID`, `VerifiedBuild`) VALUES (9501, 6, {CID}, {BUILD});"]
hot = [(H_CLASS, CID)] + [(H_SPEC, s[0]) for s in specs] + [(H_POWER, 9501)]
sql.append("INSERT INTO `hotfixes`.`hotfix_data` (`Id`, `UniqueId`, `TableHash`, `RecordId`, `Status`, `VerifiedBuild`) VALUES\n"
           + ",\n".join(f"({PUSH}, {3200000000 + n}, {h}, {r}, 1, {BUILD})" for n, (h, r) in enumerate(hot)) + ";")

# world: copy the Mage setup to class 15
w = pymysql.connect(host='127.0.0.1', user='root', password=os.environ.get('DB_PASSWORD', ''), database='world')
cur = w.cursor()
sql += [f"DELETE FROM `world`.`class_expansion_requirement` WHERE `ClassID` = {CID};",
        f"DELETE FROM `world`.`playercreateinfo` WHERE `class` = {CID};",
        f"DELETE FROM `world`.`playercreateinfo_action` WHERE `class` = {CID};",
        f"DELETE FROM `world`.`player_classlevelstats` WHERE `class` = {CID};",
        f"INSERT INTO `world`.`class_expansion_requirement` (`ClassID`, `RaceID`, `ActiveExpansionLevel`, `AccountExpansionLevel`) SELECT {CID}, `RaceID`, `ActiveExpansionLevel`, `AccountExpansionLevel` FROM `world`.`class_expansion_requirement` WHERE `ClassID` = 8;",
        f"INSERT INTO `world`.`playercreateinfo` SELECT `race`, {CID}, `map`, `position_x`, `position_y`, `position_z`, `orientation`, `npe_map`, `npe_position_x`, `npe_position_y`, `npe_position_z`, `npe_orientation`, `npe_transport_guid`, `intro_movie_id`, `intro_scene_id`, `npe_intro_scene_id` FROM `world`.`playercreateinfo` WHERE `class` = 8;",
        f"INSERT INTO `world`.`playercreateinfo_action` (`race`, `class`, `button`, `action`, `type`) SELECT `race`, {CID}, `button`, `action`, `type` FROM `world`.`playercreateinfo_action` WHERE `class` = 8;",
        f"INSERT INTO `world`.`player_classlevelstats` (`class`, `level`, `str`, `agi`, `sta`, `inte`, `spi`, `VerifiedBuild`) SELECT {CID}, `level`, `str`, `agi`, `sta`, `inte`, `spi`, `VerifiedBuild` FROM `world`.`player_classlevelstats` WHERE `class` = 8;"]
open(OUT + '.sql', 'w', encoding='utf-8').write("\n".join(sql) + "\n")
open(OUT + '_undo.sql', 'w', encoding='utf-8').write("\n".join([
    f"DELETE FROM `hotfixes`.`hotfix_data` WHERE `Id` = {PUSH};", f"DELETE FROM `hotfixes`.`chr_classes` WHERE `ID` = {CID};",
    f"DELETE FROM `hotfixes`.`chr_specialization` WHERE `ClassID` = {CID};", "DELETE FROM `hotfixes`.`chr_classes_x_power_types` WHERE `ID` = 9501;",
    f"DELETE FROM `world`.`class_expansion_requirement` WHERE `ClassID` = {CID};", f"DELETE FROM `world`.`playercreateinfo` WHERE `class` = {CID};",
    f"DELETE FROM `world`.`playercreateinfo_action` WHERE `class` = {CID};", f"DELETE FROM `world`.`player_classlevelstats` WHERE `class` = {CID};"]) + "\n")
print('written', OUT + '.sql')
