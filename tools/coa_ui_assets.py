"""Ship the CoA UI textures to the Midnight client and generate the atlas table for the CoAUI addon.
 - parses data/coa_client/patch-B/Interface/SharedXML/AtlasInfo.lua (name -> file,w,h,l,r,t,b) for every atlas whose file lives under CoAMultiCast / CoAResource / TalentFrame / CoA*
 - copies those BLPs to <client>/files/Interface/CoAUI/<same relative path> with FileDataIDs 9700000+ (mappings/coa_ui.txt)
 - writes <client>/Interface/AddOns/CoAUI/Atlas.lua : CoAUI_Atlas[name] = {fileDataID, w, h, l, r, t, b}
usage: python coa_ui_assets.py"""
import os, re, shutil

ROOT = r'C:\WowServer\Custom\data\coa_client'
CLIENT = r'C:\Games\Wow\World of Warcraft\_retail_'
BASE = 9700000
src_lua = open(os.path.join(ROOT, 'patch-B', 'Interface', 'SharedXML', 'AtlasInfo.lua'), encoding='utf-8', errors='replace').read()
pat = re.compile(r'\["([^"]+)"\]\s*=\s*\{\s*"([^"]+)"\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([\d.eE+-]+)\s*,\s*([\d.eE+-]+)\s*,\s*([\d.eE+-]+)\s*,\s*([\d.eE+-]+)')
KEEP = re.compile(r'^Interface\\+(CoA|TalentFrame|Ascension|CharacterAdvancement)', re.I)
atlas, files = {}, {}
for m in pat.finditer(src_lua):
    name, f = m.group(1), m.group(2).replace('\\\\', '\\')
    if not KEEP.search(f):
        continue
    atlas[name] = (f, *m.groups()[2:])
    files.setdefault(f, None)
print('atlases', len(atlas), 'files', len(files))
roots = [os.path.join(ROOT, d) for d in ('patch-B', 'patch-A', 'patch-X')]
mapping, missing = [], []
for i, f in enumerate(sorted(files)):
    rel = f.replace('\\', os.sep)
    found = None
    for r in roots[::-1]:          # patch-A last in the list = lowest priority; try B first
        pass
    for r in (roots[1], roots[0], roots[2]):
        for ext in ('.blp', '.BLP'):
            p = os.path.join(r, rel + ext)
            if os.path.exists(p):
                found = p
                break
        if found:
            break
    if not found:
        missing.append(f)
        continue
    fid = BASE + i
    dst = os.path.join(CLIENT, 'files', 'Interface', 'CoAUI', rel + '.blp')
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copyfile(found, dst)
    files[f] = fid
    mapping.append(f'{fid};Interface/CoAUI/{f.replace(chr(92), "/")}.blp')
open(os.path.join(CLIENT, 'mappings', 'coa_ui.txt'), 'w', newline='\n').write('\n'.join(mapping) + '\n')
lines = ['-- generated by tools/coa_ui_assets.py: CoA atlases -> {fileDataID, width, height, left, right, top, bottom}', 'CoAUI_Atlas = {']
for name, (f, w, h, l, r, t, b) in sorted(atlas.items()):
    if files.get(f):
        lines.append(f'\t["{name}"] = {{{files[f]}, {w}, {h}, {l}, {r}, {t}, {b}}},')
lines.append('}')
addon = os.path.join(CLIENT, 'Interface', 'AddOns', 'CoAUI')
os.makedirs(addon, exist_ok=True)
open(os.path.join(addon, 'Atlas.lua'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print('shipped', len(mapping), 'files; missing', len(missing), missing[:10])
