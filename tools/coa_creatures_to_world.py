"""CoA summon creatures (necromancer_creatures_raw.json) -> world SQL. Entry = 7000000 + old id.
usage: python coa_creatures_to_world.py <creatures_raw.json> <spells_raw.json> <out_prefix>"""
import json, sys, os

raw, spells_p, out = sys.argv[1], sys.argv[2], sys.argv[3]
OFF = 7000000
cr = json.load(open(raw, encoding='utf-8'))
sp = json.load(open(spells_p, encoding='utf-8'))


def q(s):
    return "'" + str(s).replace("\\", "\\\\").replace("'", "''") + "'"


def arr(s):
    return [int(x) for x in str(s).strip('{}').split(',') if x != '']


ents = ','.join(str(OFF + int(k)) for k in cr)
sql = [f"-- CoA Necromancer summon creatures -> world (generated by coa_creatures_to_world.py). Undo: {os.path.basename(out)}_undo.sql"]
undo = []
for t, k in (('creature_template', 'entry'), ('creature_template_model', 'CreatureID'), ('creature_template_difficulty', 'Entry'), ('creature_template_spell', 'CreatureID')):
    d = f"DELETE FROM `world`.`{t}` WHERE `{k}` IN ({ents});"
    sql.append(d)
    undo.append(d)
ct, cm, cd, cs = [], [], [], []
for k, c in sorted(cr.items(), key=lambda kv: int(kv[0])):
    e = OFF + int(k)
    typ = int(c['type'] or 6)
    ct.append(f"({e}, {q(c['name'])}, {q(c['sub_name'] or '')}, 35, 0, {int(c['unit_class'] or 1) or 1}, {int(c['family'] or 0)}, {typ}, "
              f"{int(c['dmg_school'] or 0)}, 2000, 2000, 0, 0, 0, 0, 0, 0)")
    disp = arr(c['display_ids']) or [int(c['model_id'] or 0)]
    for i, d in enumerate(disp):
        cm.append(f"({e}, {i}, {d}, 1, {round(1.0 / len(disp), 4)}, 69933)")
    # summons scale with the owner: level scaling + pet-like modifiers (same shape as retail Water Elemental 510)
    cd.append(f"({e}, 0, 0, 0, 864, 9, 1.125, 0.33, 1, 0.23, 0, 0, 0, 0, 0, 0, 0, 0, 268435456, 0, 0, 0, 0, 0, 0, 0, 69933)")
    for i, s in enumerate(arr(c['spells'])):
        if str(s) in sp:
            cs.append(f"({e}, {i}, {OFF + s}, 69933)")
sql.append("INSERT INTO `world`.`creature_template` (`entry`, `name`, `subname`, `faction`, `npcflag`, `unit_class`, `family`, `type`, `dmgschool`, `BaseAttackTime`, `RangeAttackTime`, `unit_flags`, `unit_flags2`, `unit_flags3`, `flags_extra`, `RequiredExpansion`, `VerifiedBuild`) VALUES\n" + ",\n".join(ct) + ";")
sql.append("INSERT INTO `world`.`creature_template_model` (`CreatureID`, `Idx`, `CreatureDisplayID`, `DisplayScale`, `Probability`, `VerifiedBuild`) VALUES\n" + ",\n".join(cm) + ";")
sql.append("INSERT INTO `world`.`creature_template_difficulty` (`Entry`, `DifficultyID`, `LevelScalingDeltaMin`, `LevelScalingDeltaMax`, `ContentTuningID`, `HealthScalingExpansion`, `HealthModifier`, `ManaModifier`, `ArmorModifier`, `DamageModifier`, `CreatureDifficultyID`, `TypeFlags`, `TypeFlags2`, `TypeFlags3`, `LootID`, `PickPocketLootID`, `SkinLootID`, `GoldMin`, `GoldMax`, `StaticFlags1`, `StaticFlags2`, `StaticFlags3`, `StaticFlags4`, `StaticFlags5`, `StaticFlags6`, `StaticFlags7`, `VerifiedBuild`) VALUES\n" + ",\n".join(cd) + ";")
if cs:
    sql.append("INSERT INTO `world`.`creature_template_spell` (`CreatureID`, `Index`, `Spell`, `VerifiedBuild`) VALUES\n" + ",\n".join(cs) + ";")
open(out + '.sql', 'w', encoding='utf-8').write("\n".join(sql) + "\n")
open(out + '_undo.sql', 'w', encoding='utf-8').write("\n".join(undo) + "\n")
print('creatures', len(ct), 'models', len(cm), 'spells', len(cs))
